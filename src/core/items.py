def get_item_name(item_id: int) -> str:
    return ITEM_NAMES.get(item_id, f"Item #{item_id}")


def get_item_pocket(item_id: int) -> str:
    """Returns the pocket category name in Gen 3 FireRed/Emerald."""
    if 0x0001 <= item_id <= 0x000C:
        return "Poké Balls"
    elif 0x015D <= item_id <= 0x0176 or item_id in (
        0x0163, 0x0164, 0x0165, 0x0166, 0x0167, 0x0168, 0x0169, 0x016A, 0x016B, 0x016C, 0x016D, 0x016E, 0x016F, 0x0170, 0x0171, 0x0172, 0x0173, 0x0174, 0x0175, 0x0176
    ):
        return "Key Items"
    return "Items"

